// ─── 转换为 WAhubX 兼容 pack 格式 ─────────────────────────────
function buildPack() {
  const scripts = SCRIPTS.map((s) => ({
    id: s.id,
    name: s.name,
    category: s.cat,
    total_turns: s.turns.length,
    min_warmup_stage: 1,
    ai_rewrite: true,
    safety: { max_daily_run_per_pair: 1, min_hours_between_runs: 20 },
    sessions: [{
      name: 'main',
      delay_from_start: '0h',
      turns: s.turns.map((t, i) => ({
        turn: i + 1,
        role: t.r,
        type: 'text',
        content_pool: t.pool,
        typing_delay_ms: [400, 1500],
        send_delay_sec: t.d,
      })),
    }],
  }));
  return {
    pack_id: 'official_zh_ab_v1',
    pack_name: '中文-双人剧本包 v1 (自然对话)',
    version: '1.0.0',
    language: 'zh',
    country: ['CN', 'TW', 'HK', 'SG', 'MY'],
    author: 'TeleHubX Official',
    total_scripts: scripts.length,
    description: `${scripts.length} 个高质量 A+B 双人对话剧本，纯中文 + 适度 emoji。每 turn 4-5 个变体，节奏快真实，覆盖日常/工作/购物/健康/家庭/财经/娱乐/旅行/节日/学习等场景。`,
    asset_pools_required: [],
    scripts,
  };
}

